export const MS_PER_SECOND = 1000;
export const MS_PER_MINUTE = 60 * MS_PER_SECOND;
export const MS_PER_HOUR = 60 * MS_PER_MINUTE;
export const MS_PER_DAY = 24 * MS_PER_HOUR;
export const MS_PER_WEEK = 7 * MS_PER_DAY;
export const MS_PER_YEAR = 365.25 * MS_PER_DAY; // Average, accounting for leap years

export const BYTES_PER_KB = 1000;
export const BYTES_PER_MB = 1000 * BYTES_PER_KB;
export const BYTES_PER_GB = 1000 * BYTES_PER_MB;

export const BYTES_PER_KIB = 1024;
export const BYTES_PER_MIB = 1024 * BYTES_PER_KIB;
export const BYTES_PER_GIB = 1024 * BYTES_PER_MIB;
